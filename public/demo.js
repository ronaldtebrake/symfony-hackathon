'use strict';

const byId = (id) => document.getElementById(id);
let latest = null;
let lastBody = '';
const bytes = (value) => typeof value !== 'number' ? '—' : value >= 1000 ? `${(value / 1000).toFixed(2)} kB` : `${value} B`;
const number = (value) => typeof value === 'number' ? value.toLocaleString() : '—';
const results = () => Object.fromEntries((latest?.results ?? []).map((item) => [item.approach, item]));

function node(tag, text, className) {
  const element = document.createElement(tag);
  if (text !== undefined) element.textContent = String(text);
  if (className) element.className = className;
  return element;
}

function renderCallRows(rows, calls) {
  rows.replaceChildren();
  calls.forEach((call, index) => {
    const row = node('tr');
    row.append(node('td', String(index + 1).padStart(2, '0')), node('td', call.name), node('td', call.status), node('td', bytes(call.resultBytes)), node('td', typeof call.durationMs === 'number' ? `${call.durationMs.toFixed(0)} ms` : '—'));
    rows.append(row);
  });
}

function renderTrace() {
  const run = results()[byId('trace-approach').value];
  renderCallRows(byId('trace-rows'), run?.brokerCalls ?? []);
  byId('trace-empty').hidden = Boolean(run?.brokerCalls?.length);
}

function render(report) {
  latest = report;
  const runs = results();
  const live = report.mode === 'live';
  byId('run-state').textContent = report.status === 'running' ? 'RUNNING' : report.status === 'failed' ? 'CHECK FAILED' : report.status === 'review_required' ? 'REVIEW REQUIRED' : report.status === 'complete' ? 'RUN COMPLETE' : 'WAITING FOR A RUN';
  byId('recorded-question').textContent = report.task ?? 'No comparison has been recorded yet. Run composer demo for the reference audit.';
  byId('mode-note').classList.toggle('live', live);
  byId('mode-note').textContent = live
    ? `LIVE INFERENCE · ${runs.code?.model ?? runs.direct?.model ?? 'Hugging Face'} · Results below come from the recorded execution.`
    : report.status === 'empty' ? 'Run composer demo in your terminal. This page follows the latest local result.' : 'REFERENCE RUN · No model was called. The MCP server, broker and isolated PHP execution are real. No token savings are claimed.';
  byId('dataset-label').textContent = report.backend === 'drupal' ? 'Drupal MCP · configured tools' : 'Editorial fixture · read only';
  for (const method of ['direct', 'code']) {
    const run = runs[method];
    byId(`${method}-bytes`).textContent = bytes(run?.toolPayloadBytes);
    byId(`${method}-calls`).textContent = run?.brokerCalls ? number(run.brokerCalls.length) : '—';
    byId(`${method}-agent-calls`).textContent = number(run?.agentToolCalls);
    byId(`${method}-tokens`).textContent = run?.providerTokens?.total != null ? number(run.providerTokens.total) : '—';
    const verification = byId(`${method}-verification`);
    verification.className = 'verification';
    verification.textContent = run?.verification?.message ?? (report.status === 'running' ? 'Execution in progress…' : 'No result yet');
    if (run?.verification?.passed === true) verification.classList.add('passed');
    if (run?.verification?.passed === false) verification.classList.add('failed');
    if (run?.verification?.passed === null) verification.classList.add('review');
  }
  const difference = byId('difference');
  difference.hidden = !(runs.direct?.verification?.passed === true && runs.code?.verification?.passed === true && runs.direct.toolPayloadBytes > 0 && typeof runs.code.toolPayloadBytes === 'number');
  if (!difference.hidden) {
    const ratio = (1 - runs.code.toolPayloadBytes / runs.direct.toolPayloadBytes) * 100;
    difference.textContent = `${Math.abs(ratio).toFixed(0)}% ${ratio >= 0 ? 'less' : 'more'} payload`;
  }
  const codeRun = runs.code;
  const programs = codeRun?.programs ?? [];
  byId('program').textContent = programs.length ? programs.map((source, index) => programs.length > 1 ? `// Attempt ${index + 1}\n${source}` : source).join('\n\n') : '// No PHP program has been recorded for this run.';
  byId('program-caption').textContent = programs.length ? live ? 'Model-generated PHP · exact source submitted to gVisor' : 'Reference PHP · executed in gVisor, not generated by a model' : 'The submitted program will appear here after a Code Mode execution.';
  const auditRun = codeRun?.report ? codeRun : runs.direct;
  const audit = auditRun?.report;
  const findings = Array.isArray(audit?.findings) ? audit.findings : [];
  const originalAudit = !report.questionId || report.questionId === 'audit';
  byId('findings-list').hidden = !originalAudit;
  byId('result-json').hidden = originalAudit || audit == null;
  byId('result-json').textContent = audit == null ? '' : JSON.stringify(audit, null, 2);
  byId('findings-count').hidden = !originalAudit;
  byId('findings-count').textContent = number(findings.length);
  byId('findings-summary').textContent = !audit ? 'No result yet' : originalAudit ? `${number(audit.audited)} articles checked · ${findings.length} findings` : report.questionId === 'impact' ? 'Issue groups and shared-image impact' : 'Custom answer · review required';
  byId('findings-source').textContent = auditRun?.approach === 'direct' ? 'Direct tool-calling result' : 'Code Mode result';
  const list = byId('findings-list');
  list.replaceChildren();
  findings.forEach((finding) => {
    const row = node('div', undefined, 'finding');
    row.append(node('span', `#${finding.id}`, 'finding-id'));
    const body = node('div', undefined, 'finding-body');
    body.append(node('div', finding.title, 'finding-title'));
    (Array.isArray(finding.issues) ? finding.issues : []).forEach((issue) => body.append(node('span', issue === 'missing_description' ? 'Missing description' : issue === 'missing_alt' ? 'Missing alt text' : issue, 'issue')));
    row.append(body);
    list.append(row);
  });
  byId('source-note').textContent = report.backend === 'drupal' ? 'Connected through MCP to the configured Drupal Tool API bridge. Review external findings on the site; fixture verification does not apply.' : 'The fixture is a real PHP MCP server. Both paths use the same dataset, authorization and batched tools.';
  if (report.createdAt) byId('updated-at').textContent = `Comparison recorded · ${new Date(report.createdAt).toLocaleString()}`;
  renderTrace();
}

document.querySelectorAll('[role="tablist"]').forEach((tablist) => {
  const tabs = Array.from(tablist.querySelectorAll('[role="tab"]'));
  const selectTab = (tab) => {
    tabs.forEach((item) => {
      const active = item === tab;
      item.setAttribute('aria-selected', String(active));
      item.tabIndex = active ? 0 : -1;
      byId(item.getAttribute('aria-controls')).hidden = !active;
    });
  };
  tabs.forEach((tab, index) => {
    tab.addEventListener('click', () => selectTab(tab));
    tab.addEventListener('keydown', (event) => {
      if (!['ArrowLeft', 'ArrowRight', 'Home', 'End'].includes(event.key)) return;
      event.preventDefault();
      const target = event.key === 'Home' ? 0 : event.key === 'End' ? tabs.length - 1 : (index + (event.key === 'ArrowRight' ? 1 : -1) + tabs.length) % tabs.length;
      selectTab(tabs[target]);
      tabs[target].focus();
    });
  });
});
byId('trace-approach').addEventListener('change', renderTrace);
async function refresh() {
  try {
    const response = await fetch('/demo/report', {cache: 'no-store', credentials: 'same-origin'});
    if (!response.ok) throw new Error('Report unavailable');
    const body = await response.text();
    if (body !== lastBody) {
      render(JSON.parse(body));
      lastBody = body;
    }
  } catch {
    byId('run-state').textContent = 'REPORT UNAVAILABLE';
  } finally {
    setTimeout(refresh, 2500);
  }
}
refresh();

function renderSecurity(report) {
  const state = byId('security-state');
  state.textContent = report.status === 'complete' ? '3 CHECKS PASSED' : report.status === 'running' ? 'RUNNING' : report.status === 'failed' ? 'PROOF FAILED' : 'NOT RUN';
  byId('security-note').textContent = report.status === 'empty'
    ? 'No security proof has been recorded. Results appear only after execution.'
    : report.error ? `The proof could not finish: ${report.error}. No successful execution is implied.`
    : report.status === 'running' ? 'The operator is running fixed probes. This page follows the host-recorded observations.'
    : report.status === 'failed' ? 'PROOF FAILED · At least one required observation is missing or incorrect. Inspect the traces; a configured limit alone does not prove it was enforced.'
    : 'REAL EXECUTION · Fixed PHP probes, real MCP and gVisor. No model was called. Expand each trace to inspect the evidence.';
  const cards = byId('security-cases');
  cards.replaceChildren();
  const outcomes = {authorized_read: 'Read allowed', unauthorized_call: 'Call blocked', infinite_loop: 'Loop terminated'};
  for (const item of report.cases ?? []) {
    const card = node('article', undefined, 'security-card');
    const heading = node('div', undefined, 'card-heading');
    heading.append(node('h3', item.title), node('span', item.passed === true ? outcomes[item.id] ?? 'Passed' : 'Check failed', item.passed === true ? 'proof-outcome passed' : 'proof-outcome failed'));
    card.append(heading);
    const source = node('pre', undefined, 'proof-source');
    source.tabIndex = 0;
    source.append(node('code', item.code));
    card.append(source);
    const facts = node('dl', undefined, 'proof-facts');
    for (const [label, value] of [
      ['Observed', item.reason ?? 'succeeded'],
      ['Elapsed', typeof item.durationMs === 'number' ? `${item.durationMs.toFixed(0)} ms` : '—'],
      ['Container', item.containerRemoved === true ? 'Removed · checked' : item.containerRemoved === false ? 'Still present' : 'Not confirmed'],
    ]) {
      const row = node('div');
      row.append(node('dt', label), node('dd', value));
      facts.append(row);
    }
    card.append(facts);
    if (item.id === 'authorized_read' && item.value != null) card.append(node('p', `Published articles returned: ${JSON.stringify(item.value)}`, 'proof-result'));
    const calls = node('ul', undefined, 'proof-calls');
    for (const call of item.toolCalls ?? []) calls.append(node('li', `${call.name} · ${call.status}${call.reason ? ` (${call.reason})` : ''}`));
    card.append(calls);
    const details = node('details', undefined, 'proof-details');
    details.append(node('summary', 'Inspect execution trace'));
    const evidence = node('pre', JSON.stringify(item, null, 2));
    evidence.tabIndex = 0;
    details.append(evidence);
    card.append(details);
    cards.append(card);
  }
  byId('security-record').textContent = report.createdAt
    ? `Recorded ${new Date(report.createdAt).toLocaleString()} · Runtime required: ${report.runtime} · Image: ${report.image}` : '';
}

let lastSecurityBody = '';
async function refreshSecurity() {
  try {
    const response = await fetch('/demo/security-report', {cache: 'no-store', credentials: 'same-origin'});
    if (!response.ok) throw new Error('Security report unavailable');
    const body = await response.text();
    if (body !== lastSecurityBody) {
      renderSecurity(JSON.parse(body));
      lastSecurityBody = body;
    }
  } catch {
    lastSecurityBody = '';
    byId('security-state').textContent = 'REPORT UNAVAILABLE';
    byId('security-note').textContent = 'The security report could not be loaded. Any observations below are from the previous successful refresh.';
  } finally {
    setTimeout(refreshSecurity, 2500);
  }
}
refreshSecurity();

let codexCapture = null;
let selectedCodexTurn = 0;
const turnButtons = Array.from(document.querySelectorAll('[data-codex-turn]'));

function renderCodexTurn(index) {
  if (!codexCapture) return;
  selectedCodexTurn = index;
  const turn = codexCapture.turns[index];
  const calls = turn.items.filter((item) => item.type === 'mcpToolCall');
  const execution = calls.find((item) => item.tool === 'php_execute');
  const result = execution.result.structuredContent;
  const value = result.value;
  turnButtons.forEach((button) => button.setAttribute('aria-pressed', String(Number(button.dataset.codexTurn) === index)));
  byId('codex-turn-label').textContent = index === 0 ? 'Original question · recorded' : 'Follow-up · recorded';
  byId('codex-prompt').textContent = turn.prompt;
  byId('codex-program').textContent = execution.arguments.code;
  byId('codex-program').parentElement.scrollTop = 0;
  byId('codex-program-caption').textContent = `Codex-generated PHP · executed in gVisor · ${result.durationMs.toFixed(0)} ms runner time`;
  byId('codex-call-count').textContent = result.toolCalls.length;
  renderCallRows(byId('codex-call-rows'), result.toolCalls);
  byId('codex-answer').textContent = JSON.stringify(value, null, 2);
  byId('codex-answer').scrollTop = 0;
  byId('codex-response').textContent = turn.items.filter((item) => item.type === 'agentMessage' && item.phase === 'final_answer').map((item) => item.text).join('\n\n');
  const mcpCalls = byId('codex-mcp-calls');
  mcpCalls.replaceChildren();
  for (const call of calls) {
    const details = node('details', undefined, 'proof-details');
    details.append(node('summary', `${call.tool} · ${call.status}`));
    const trace = node('pre', JSON.stringify(call, null, 2));
    trace.tabIndex = 0;
    details.append(trace);
    mcpCalls.append(details);
  }
  const detail = byId('codex-result-detail');
  detail.replaceChildren();
  if (index === 0) {
    byId('codex-result-summary').textContent = `${value.total_audited} articles audited · ${value.affected_count} affected`;
    detail.append(node('li', `Affected IDs: ${value.affected_articles.map((article) => article.id).join(', ')}`));
  } else {
    byId('codex-result-summary').textContent = `${value.total_audited} articles rechecked · ${value.shared_hero_image_fix_count} shared-image fixes`;
    for (const fix of value.hero_image_alt_fixes_ranked_by_impact) {
      detail.append(node('li', `Image ${fix.image_id} → articles ${fix.affected_article_ids.join(', ')} (${fix.affected_article_count} helped)`));
    }
    detail.append(node('li', `Missing descriptions: ${value.meta_description_fixes.map((article) => article.id).join(', ')}`));
  }
  const verified = codexCapture.verification?.[index === 0 ? 'auditMatchesIndependentOracle' : 'impactMatchesIndependentOracle'];
  byId('codex-validation').textContent = verified === true ? 'Recorded fixture check: matched the independent expected result.' : 'No successful fixture check recorded for this turn.';
}

turnButtons.forEach((button) => button.addEventListener('click', () => renderCodexTurn(Number(button.dataset.codexTurn))));

// Present only the reviewed capture. Code is text, never HTML or executable JS.
const phpPresentation = byId('php-presentation');
byId('present-php').addEventListener('click', () => {
  if (!codexCapture) return;
  const source = byId('codex-program').textContent;
  const lines = source.split('\n');
  const code = byId('php-presentation-code');
  code.replaceChildren();
  lines.forEach((line, index) => {
    const row = node('span', line + (index < lines.length - 1 ? '\n' : ''), 'php-source-line');
    row.dataset.line = index + 1;
    row.classList.toggle('php-tool-line', line.includes('$tools->call('));
    code.append(row);
  });
  byId('php-presentation-title').textContent = selectedCodexTurn === 0 ? '01 · Audit the published articles.' : '02 · Rank the shared-image fixes.';
  const date = new Date(codexCapture.recordedAt).toLocaleDateString('en-GB', {day: 'numeric', month: 'long', year: 'numeric', timeZone: 'Europe/Amsterdam'});
  byId('php-presentation-meta').textContent = `Recorded ${date} · ${byId('codex-program-caption').textContent}`;
  byId('php-copy-status').textContent = '';
  const navigation = byId('php-source-nav');
  navigation.replaceChildren();
  const sections = selectedCodexTurn === 0
    ? [['List articles', '$listed ='], ['Read batches', '$articles ='], ['Find issues', '$affected ='], ['Return findings', 'return [']]
    : [['Read articles', '$listed ='], ['Group images', '$imageUsage ='], ['Rank fixes', 'usort($imageFixes,'], ['Return plan', 'return [']];
  for (const [label, marker] of sections) {
    const index = lines.findIndex((line) => line.startsWith(marker));
    if (index < 0) continue;
    const button = node('button', label);
    button.type = 'button';
    button.addEventListener('click', () => {
      navigation.querySelectorAll('button').forEach((item) => item.removeAttribute('aria-current'));
      button.setAttribute('aria-current', 'location');
      code.querySelectorAll('.php-source-focus').forEach((row) => row.classList.remove('php-source-focus'));
      const row = code.children[index];
      row.classList.add('php-source-focus');
      row.scrollIntoView({block: 'start', behavior: 'instant'});
    });
    navigation.append(button);
  }
  phpPresentation.showModal();
  byId('php-presentation-source').scrollTop = 0;
  byId('php-presentation-source').scrollLeft = 0;
});
byId('close-php').addEventListener('click', () => phpPresentation.close());
byId('copy-php').addEventListener('click', async () => {
  try {
    await navigator.clipboard.writeText(byId('php-presentation-code').textContent);
    byId('php-copy-status').textContent = 'Exact submitted PHP copied.';
  } catch {
    byId('php-copy-status').textContent = 'Clipboard unavailable. Select and copy the source above.';
  }
});

async function loadCodexCapture() {
  try {
    const response = await fetch('/demo/codex-report', {cache: 'no-store', credentials: 'same-origin'});
    if (!response.ok) throw new Error('Capture unavailable');
    const report = await response.json();
    if (report.status === 'empty') {
      byId('codex-state').textContent = 'NO CAPTURE';
      byId('codex-note').textContent = 'The recorded Codex capture is not available in this checkout.';
      return;
    }
    // This viewer handles the reviewed two-turn Symfony rehearsal, not arbitrary imports.
    if (report.backend !== 'Symfony fixture' || !Array.isArray(report.turns) || report.turns.length !== 2) throw new Error('Invalid capture');
    const executions = report.turns.map((turn) => {
      const runs = turn.items.filter((item) => item.type === 'mcpToolCall' && item.tool === 'php_execute');
      if (turn.status !== 'completed' || typeof turn.prompt !== 'string' || runs.length !== 1
        || runs[0].status !== 'completed' || runs[0].error || typeof runs[0].arguments?.code !== 'string'
        || !Array.isArray(runs[0].result?.structuredContent?.toolCalls)) throw new Error('Incomplete capture');
      return runs[0].result.structuredContent;
    });
    codexCapture = report;
    renderCodexTurn(0);
    byId('codex-state').textContent = '2 RECORDED TURNS';
    byId('codex-note').textContent = 'Two prompts in one Codex desktop chat; both responses and PHP programs were generated live. This capture matches the fresh judge-demo rehearsal. Conversations stay in Codex.';
    const recorded = new Date(report.recordedAt).toLocaleString('en-GB', {day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit', timeZone: 'Europe/Amsterdam', timeZoneName: 'short'});
    const callCount = executions.reduce((count, execution) => count + execution.toolCalls.length, 0);
    byId('codex-provenance').textContent = `${report.client} · ${report.backend} · ${executions.length} PHP executions · ${callCount} upstream calls · Recorded ${recorded}`;
    byId('codex-session-note').textContent = 'Audit and follow-up are from the same recorded Codex chat, with one PHP execution per turn. This export does not include the model or MCP process identity.';
    byId('codex-evidence').hidden = false;
  } catch {
    codexCapture = null;
    byId('codex-evidence').hidden = true;
    byId('codex-state').textContent = 'CAPTURE UNAVAILABLE';
    byId('codex-note').textContent = 'The saved Codex evidence could not be loaded. No execution or successful result is implied.';
  }
}
loadCodexCapture();
