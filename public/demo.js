const staticDocumentation = document.documentElement.dataset.static === 'true';
const evidenceUrl = (path) => staticDocumentation ? `evidence/${path.split('/').pop()}.json` : path;
const poll = (callback, delay) => { if (!staticDocumentation) setTimeout(callback, delay); };
'use strict';

const byId = (id) => document.getElementById(id);
let latest = null;
let lastBody = '';
const bytes = (value) => typeof value !== 'number' ? '—' : value >= 1000 ? `${(value / 1000).toFixed(2)} kB` : `${value} B`;
const number = (value) => typeof value === 'number' ? value.toLocaleString() : '—';
const results = () => Object.fromEntries((latest?.results ?? []).map((item) => [item.approach, item]));

function node(tag, text, className) {
  const element = document.createElement(tag);
  if (text !== undefined) element.textContent = String(text);
  if (className) element.className = className;
  return element;
}

function renderCallRows(rows, calls) {
  rows.replaceChildren();
  calls.forEach((call, index) => {
    const row = node('tr');
    row.append(node('td', String(index + 1).padStart(2, '0')), node('td', call.name), node('td', call.status), node('td', bytes(call.resultBytes)), node('td', typeof call.durationMs === 'number' ? `${call.durationMs.toFixed(0)} ms` : '—'));
    rows.append(row);
  });
}

function renderTrace() {
  const run = results()[byId('trace-approach').value];
  renderCallRows(byId('trace-rows'), run?.brokerCalls ?? []);
  byId('trace-empty').hidden = Boolean(run?.brokerCalls?.length);
}

function render(report) {
  latest = report;
  const runs = results();
  const live = report.mode === 'live';
  byId('run-state').textContent = report.status === 'running' ? 'RUNNING' : report.status === 'failed' ? 'CHECK FAILED' : report.status === 'review_required' ? 'REVIEW REQUIRED' : report.status === 'complete' ? 'RUN COMPLETE' : 'WAITING FOR A RUN';
  byId('recorded-question').textContent = report.task ?? 'No comparison has been recorded yet. Run composer demo for the reference audit.';
  byId('mode-note').classList.toggle('live', live);
  byId('mode-note').textContent = live
    ? `LIVE INFERENCE · ${runs.code?.model ?? runs.direct?.model ?? 'Hugging Face'} · Results below come from the recorded execution.`
    : report.status === 'empty' ? 'Run composer demo in your terminal. This page follows the latest local result.' : 'REFERENCE RUN · No model was called. The MCP server, broker and isolated PHP execution are real. No token savings are claimed.';
  byId('dataset-label').textContent = report.backend === 'drupal' ? 'Drupal MCP · configured tools' : 'Editorial fixture · read only';
  for (const method of ['direct', 'code']) {
    const run = runs[method];
    byId(`${method}-bytes`).textContent = bytes(run?.toolPayloadBytes);
    byId(`${method}-calls`).textContent = run?.brokerCalls ? number(run.brokerCalls.length) : '—';
    byId(`${method}-agent-calls`).textContent = number(run?.agentToolCalls);
    byId(`${method}-tokens`).textContent = run?.providerTokens?.total != null ? number(run.providerTokens.total) : '—';
    const verification = byId(`${method}-verification`);
    verification.className = 'verification';
    verification.textContent = run?.verification?.message ?? (report.status === 'running' ? 'Execution in progress…' : 'No result yet');
    if (run?.verification?.passed === true) verification.classList.add('passed');
    if (run?.verification?.passed === false) verification.classList.add('failed');
    if (run?.verification?.passed === null) verification.classList.add('review');
  }
  const difference = byId('difference');
  difference.hidden = !(runs.direct?.verification?.passed === true && runs.code?.verification?.passed === true && runs.direct.toolPayloadBytes > 0 && typeof runs.code.toolPayloadBytes === 'number');
  if (!difference.hidden) {
    const ratio = (1 - runs.code.toolPayloadBytes / runs.direct.toolPayloadBytes) * 100;
    difference.textContent = `${Math.abs(ratio).toFixed(0)}% ${ratio >= 0 ? 'less' : 'more'} payload`;
  }
  const codeRun = runs.code;
  const programs = codeRun?.programs ?? [];
  byId('program').textContent = programs.length ? programs.map((source, index) => programs.length > 1 ? `// Attempt ${index + 1}\n${source}` : source).join('\n\n') : '// No PHP program has been recorded for this run.';
  byId('program-caption').textContent = programs.length ? live ? 'Model-generated PHP · exact source submitted to gVisor' : 'Reference PHP · executed in gVisor, not generated by a model' : 'The submitted program will appear here after a Code Mode execution.';
  const auditRun = codeRun?.report ? codeRun : runs.direct;
  const audit = auditRun?.report;
  const findings = Array.isArray(audit?.findings) ? audit.findings : [];
  const originalAudit = !report.questionId || report.questionId === 'audit';
  byId('findings-list').hidden = !originalAudit;
  byId('result-json').hidden = originalAudit || audit == null;
  byId('result-json').textContent = audit == null ? '' : JSON.stringify(audit, null, 2);
  byId('findings-count').hidden = !originalAudit;
  byId('findings-count').textContent = number(findings.length);
  byId('findings-summary').textContent = !audit ? 'No result yet' : originalAudit ? `${number(audit.audited)} articles checked · ${findings.length} findings` : report.questionId === 'impact' ? 'Issue groups and shared-image impact' : 'Custom answer · review required';
  byId('findings-source').textContent = auditRun?.approach === 'direct' ? 'Direct tool-calling result' : 'Code Mode result';
  const list = byId('findings-list');
  list.replaceChildren();
  findings.forEach((finding) => {
    const row = node('div', undefined, 'finding');
    row.append(node('span', `#${finding.id}`, 'finding-id'));
    const body = node('div', undefined, 'finding-body');
    body.append(node('div', finding.title, 'finding-title'));
    (Array.isArray(finding.issues) ? finding.issues : []).forEach((issue) => body.append(node('span', issue === 'missing_description' ? 'Missing description' : issue === 'missing_alt' ? 'Missing alt text' : issue, 'issue')));
    row.append(body);
    list.append(row);
  });
  byId('source-note').textContent = report.backend === 'drupal' ? 'Connected through MCP to the configured Drupal Tool API bridge. Review external findings on the site; fixture verification does not apply.' : 'The fixture is a real PHP MCP server. Both paths use the same dataset, authorization and batched tools.';
  renderTrace();
}

document.querySelectorAll('[role="tablist"]').forEach((tablist) => {
  const tabs = Array.from(tablist.querySelectorAll('[role="tab"]'));
  const selectTab = (tab) => {
    tabs.forEach((item) => {
      const active = item === tab;
      item.setAttribute('aria-selected', String(active));
      item.tabIndex = active ? 0 : -1;
      byId(item.getAttribute('aria-controls')).hidden = !active;
    });
  };
  tabs.forEach((tab, index) => {
    tab.addEventListener('click', () => selectTab(tab));
    tab.addEventListener('keydown', (event) => {
      if (!['ArrowLeft', 'ArrowRight', 'Home', 'End'].includes(event.key)) return;
      event.preventDefault();
      const target = event.key === 'Home' ? 0 : event.key === 'End' ? tabs.length - 1 : (index + (event.key === 'ArrowRight' ? 1 : -1) + tabs.length) % tabs.length;
      selectTab(tabs[target]);
      tabs[target].focus();
    });
  });
});
